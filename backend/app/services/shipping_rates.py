DEFAULT_ZONE = "zone3"


def zone_for_country(country: str | None) -> str:
    """Which rate column a shopper in ``country`` is quoted."""
    return ZONE_BY_COUNTRY.get((country or "").strip().upper(), DEFAULT_ZONE)


def lookup(zone: str, service: str, weight_grams: int) -> int | None:
    """Rate in JPY, or None when the service will not carry the weight."""
    for limit, price in RATES.get(zone, {}).get(service, []):
        if weight_grams <= limit:
            return price
    return None


#: Sea mail. Cheap, and one to three months in transit, which is why it is
#: not what "cheapest" should mean by default for someone tracking a release.
SURFACE_SERVICES = frozenset({"surface_parcel"})


def cheapest(zone: str, weight_grams: int, air_only: bool = False) -> tuple[str, int] | None:
    """The least expensive service that will actually take the shipment."""
    quotes = [
        (service, price)
        for service in SERVICES
        if not (air_only and service in SURFACE_SERVICES)
        if (price := lookup(zone, service, weight_grams)) is not None
    ]
    if not quotes:
        return None
    return min(quotes, key=lambda quote: quote[1])


def heaviest(zone: str, service: str) -> int:
    """Top of a service's chart, so callers can explain a refusal."""
    steps = RATES.get(zone, {}).get(service, [])
    return steps[-1][0] if steps else 0


