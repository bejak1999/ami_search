"""AmiAmi's published international shipping rates.

The RATES table below is transcribed from the shop's own charts:
  support.amiami.com/hc/en-us/articles/11210530387993  (small packet)
  support.amiami.com/hc/en-us/articles/11212135920153  (parcel and EMS)

Each entry is the price in JPY for a shipment weighing up to the stated
number of grams, so a lookup takes the first bracket at or above the actual
weight. Small packet stops at 2 kg; parcel and EMS run to 30 kg, and the
parcel services simply are not offered for the lightest shipments, which is
why their tables start higher up. AmiAmi revises these charts from time to
time; regenerate the table rather than editing individual numbers.
"""
